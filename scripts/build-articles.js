const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const ARTICLES_DIR = path.join(__dirname, '../src/content/articles');
const OUTPUT_JSON = path.join(__dirname, '../src/data/articles.json');
const OUTPUT_TS = path.join(__dirname, '../src/data/articles.ts');

function main() {
  console.log('Building precompiled articles for Cloudflare Pages / Edge runtime...');

  if (!fs.existsSync(ARTICLES_DIR)) {
    console.error('Articles directory not found at:', ARTICLES_DIR);
    process.exit(1);
  }

  const fileNames = fs.readdirSync(ARTICLES_DIR).filter((f) => f.endsWith('.md'));
  console.log(`Found ${fileNames.length} markdown articles.`);

  const articles = fileNames
    .map((fileName) => {
      const fullPath = path.join(ARTICLES_DIR, fileName);
      const fileContents = fs.readFileSync(fullPath, 'utf8');
      const { data, content } = matter(fileContents);

      const headings = Array.isArray(data.headings) ? data.headings : [];

      return {
        slug: data.slug || fileName.replace(/\.md$/, ''),
        title: data.title || 'Untitled',
        originalUrl: data.originalUrl || '',
        publishedAt: data.publishedAt || new Date().toISOString(),
        modifiedAt: data.modifiedAt || data.publishedAt || new Date().toISOString(),
        excerpt: data.excerpt || '',
        category: data.category || 'General',
        readingTime: Number(data.readingTime) || 5,
        wordCount: Number(data.wordCount) || 1000,
        featuredImage: data.featuredImage || '/images/articles/placeholder.webp',
        featuredImageAlt: data.featuredImageAlt || data.title || '',
        headings,
        content: content.trim(),
      };
    })
    .sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime());

  // Ensure output directory exists
  const outputDir = path.dirname(OUTPUT_JSON);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }

  fs.writeFileSync(OUTPUT_JSON, JSON.stringify(articles, null, 2), 'utf8');
  console.log(`Saved ${articles.length} articles to ${OUTPUT_JSON}`);

  const tsContent = `// Auto-generated by scripts/build-articles.js. Do not edit directly.
import type { Article } from "@/types/article";
import articlesData from "./articles.json";

export const PRECOMPILED_ARTICLES: Article[] = articlesData as Article[];
`;
  fs.writeFileSync(OUTPUT_TS, tsContent, 'utf8');
  console.log(`Generated TypeScript wrapper at ${OUTPUT_TS}`);
}

main();
